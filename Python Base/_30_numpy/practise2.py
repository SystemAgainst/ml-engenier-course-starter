'''Индексация, срезы, copy и view'''
import numpy as np

matrix = np.arange(1, 37).reshape(6, 6)
print(matrix)
print(f"Вторая строка:          {matrix[1, :]}   shape={matrix[1, :].shape}")
print(f"Последний столбец:      {matrix[:, -1]}  shape={matrix[:, -1].shape}")
print(f"Центральный блок 2 × 2:\n{matrix[2:4, 2:4]}  shape={matrix[2:4, 2:4].shape}")

print(f"разверни порядок строк и столбцов: {matrix[::-1,::-1]}")
print(f"разверни порядок строк и столбцов с помощью библиотеки: {np.flip(matrix, axis=(0, 1))}") # np.flip делает то же самое, но ось указывается аргументом axis. Также, Срез [::-1] в numpy возвращает вид (view), а не новый массив. Данные в памяти те же. Изменение вида изменит исходный массив.

'''
Boolean mask (логическая маска) — это массив той же формы, что и исходный, но заполненный значениями True и False. Маска работает как фильтр
'''
mask = matrix % 2 == 0 #
matrix[mask] = 0
print(f"Замени все чётные элементы на 0 через boolean maskЭ: {matrix}")

'''
Срез в numpy (matrix[1:4, 1:4] и подобные) возвращает вид, а не копию. Вид делит данные с исходным массивом. Поэтому если вы измените срез, изменится и исходный массив

В numpy срез — это вид. Вид не копирует данные. Вид хранит ссылку на тот же буфер памяти и описывает, какие элементы из него брать. Поэтому изменение через вид видно в исходном массиве, и наоборот.

это правило верно для срезов ([a:b], [:, c], [::2]) и для reshape, transpose, np.flip. Но не верно для fancy indexing (индексация списком индексов, например matrix[[0, 2]]) и для логической маски (matrix[mask]). Эти операции возвращают копию.

Как проверить, вид это или копия:
1.  Атрибут .base.
Если .base указывает на исходный массив — это вид. Если .base is None — это самостоятельный массив (копия или исходник).

2. Изменить и сравнить. Это то, что вы и делаете в задаче.
'''
print(f"\nДо изменения среза: {matrix}")

block = matrix[1:4, 1:4] # срез = вид, не копия
block[0, 0] = 999 # меняем один элемент среза
print(f"\nПосле изменения среза: {matrix}")

print(block.base is matrix)   # True  -> это вид

# Случай A: срез без .copy() -> вид
a = matrix[1:4, 1:4]
a[0, 0] = 100
print(f"A: matrix[1,1]: {matrix[1,1]}") # 100 -> изменился

# Случай B: срез с .copy() -> копия
b = matrix[1:4, 1:4].copy()
b[0, 0] = 200
print("B: matrix[1,1] =", matrix[1, 1])   # 100 -> не изменился

# Случай C: fancy indexing -> копия
c = matrix[[1, 2], :]
c[0, 0] = 300
print("C: matrix[1,0] =", matrix[1, 0])   # 7 -> не изменился
'''
случай   операция               тип     matrix изменился?
-------  ---------------------  ------  -----------------
A        matrix[1:4, 1:4]       вид     да
B        matrix[1:4, 1:4].copy  копия   нет
C        matrix[[1, 2], :]      копия   нет
'''